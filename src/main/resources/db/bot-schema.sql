    id INTEGER PRIMARY KEY CHECK (id = 1),
    prompt VARCHAR(8000) NOT NULL,
    revision BIGINT NOT NULL
);
INSERT INTO bot_content_boundary(id,prompt,revision) SELECT 1,'',0 WHERE NOT EXISTS (SELECT 1 FROM bot_content_boundary WHERE id=1);

