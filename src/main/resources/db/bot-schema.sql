CREATE TABLE IF NOT EXISTS bot_settings (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    ai_enabled BOOLEAN NOT NULL,
    wiki_enabled BOOLEAN NOT NULL,
    builtin_images_enabled BOOLEAN NOT NULL,
    keyword_replies_enabled BOOLEAN NOT NULL,
    group_require_at BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS conversation_memory (
    owner_key VARCHAR(200) NOT NULL,
    ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
    user_text VARCHAR(4000) NOT NULL,
    assistant_text VARCHAR(4000) NOT NULL,
    is_summary BOOLEAN NOT NULL,
    PRIMARY KEY(owner_key, ordinal)
);
CREATE TABLE IF NOT EXISTS group_memory (
    owner_key VARCHAR(200) NOT NULL,
    ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
    user_id VARCHAR(20) NOT NULL,
    sender_name VARCHAR(200) NOT NULL,
    content VARCHAR(4000) NOT NULL,
    message_time BIGINT NOT NULL,
    is_bot BOOLEAN NOT NULL,
    is_summary BOOLEAN NOT NULL,
    PRIMARY KEY(owner_key, ordinal)
);
CREATE TABLE IF NOT EXISTS group_memory_summary_attempt (
    self_id VARCHAR(20) NOT NULL,
    group_id VARCHAR(20) NOT NULL,
    last_attempt BIGINT NOT NULL,
    PRIMARY KEY(self_id, group_id)
);
CREATE TABLE IF NOT EXISTS bot_persona (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    prompt VARCHAR(8000) NOT NULL
);
CREATE TABLE IF NOT EXISTS image_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_name VARCHAR(255) NOT NULL,
    stored_name VARCHAR(64) NOT NULL UNIQUE,
    content_type VARCHAR(40) NOT NULL,
    byte_size BIGINT NOT NULL,
    created_at VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS reply_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword VARCHAR(200) NOT NULL,
    match_type VARCHAR(10) NOT NULL CHECK (match_type IN ('EXACT', 'CONTAINS')),
    reply_text VARCHAR(4000) NOT NULL,
    image_id BIGINT REFERENCES image_asset(id),
    enabled BOOLEAN NOT NULL,
    priority INTEGER NOT NULL CHECK (priority BETWEEN 0 AND 999),
    action_type VARCHAR(30) DEFAULT 'REPLY' NOT NULL
);
ALTER TABLE reply_rule ADD COLUMN IF NOT EXISTS action_type VARCHAR(30) DEFAULT 'REPLY' NOT NULL;
CREATE TABLE IF NOT EXISTS bot_migration (version VARCHAR(80) PRIMARY KEY);
CREATE INDEX IF NOT EXISTS reply_rule_order ON reply_rule(enabled, priority DESC, id);
CREATE TABLE IF NOT EXISTS group_policy (
    self_id VARCHAR(20) NOT NULL,
    group_id VARCHAR(20) NOT NULL,
    group_name VARCHAR(200) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    trigger_mode VARCHAR(10) NOT NULL DEFAULT 'ALL',
    keywords VARCHAR(500) NOT NULL DEFAULT '',
    cooldown_seconds INTEGER NOT NULL DEFAULT 30,
    daily_limit INTEGER NOT NULL DEFAULT 50,
    max_input_chars INTEGER NOT NULL DEFAULT 500,
    max_output_tokens INTEGER NOT NULL DEFAULT 256,
    context_turns INTEGER NOT NULL DEFAULT 3,
    follow_up_seconds INTEGER NOT NULL DEFAULT 60,
    PRIMARY KEY (self_id, group_id)
);
ALTER TABLE group_policy ALTER COLUMN trigger_mode SET DEFAULT 'ALL';
ALTER TABLE group_policy ADD COLUMN IF NOT EXISTS auto_reply_rate DOUBLE PRECISION DEFAULT 1 NOT NULL CHECK (auto_reply_rate >= 0 AND auto_reply_rate <= 1);
CREATE TABLE IF NOT EXISTS group_ai_usage (
    self_id VARCHAR(20) NOT NULL,
    group_id VARCHAR(20) NOT NULL,
    usage_day DATE NOT NULL,
    call_count INTEGER NOT NULL,
    last_attempt BIGINT NOT NULL,
    PRIMARY KEY (self_id, group_id, usage_day),
    FOREIGN KEY (self_id, group_id) REFERENCES group_policy(self_id, group_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS knowledge_base (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    keywords VARCHAR(4000) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS knowledge_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_id BIGINT NOT NULL REFERENCES knowledge_base(id) ON DELETE CASCADE,
    original_name VARCHAR(200) NOT NULL,
    stored_name VARCHAR(50) NOT NULL,
    byte_size BIGINT NOT NULL,
    created_at VARCHAR(40) NOT NULL,
    content CLOB NOT NULL
);

CREATE TABLE IF NOT EXISTS bot_wows (id INTEGER PRIMARY KEY CHECK(id=1), enabled BOOLEAN NOT NULL);
CREATE TABLE IF NOT EXISTS tag_image_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_key VARCHAR(64) NOT NULL,
    image_key VARCHAR(64) NOT NULL,
    selected_at BIGINT NOT NULL,
    UNIQUE(recipient_key, image_key)
);
CREATE INDEX IF NOT EXISTS tag_image_history_time ON tag_image_history(selected_at);
CREATE TABLE IF NOT EXISTS group_style_profile (
    self_id VARCHAR(20) NOT NULL,
    group_id VARCHAR(20) NOT NULL,
    profile VARCHAR(4000) NOT NULL DEFAULT '{}',
    revision BIGINT NOT NULL DEFAULT 0,
    last_attempt BIGINT NOT NULL DEFAULT 0,
    updated_at BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY(self_id,group_id),
    FOREIGN KEY(self_id,group_id) REFERENCES group_policy(self_id,group_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS group_learning_budget (
    id INTEGER PRIMARY KEY CHECK(id=1),
    usage_day DATE NOT NULL,
    attempts INTEGER NOT NULL,
    last_attempt BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS learning_settings (
    id INTEGER PRIMARY KEY CHECK(id=1),
    enabled BOOLEAN NOT NULL
);
INSERT INTO learning_settings(id,enabled) SELECT 1,TRUE WHERE NOT EXISTS(SELECT 1 FROM learning_settings WHERE id=1);
CREATE TABLE IF NOT EXISTS group_learning_settings (
    self_id VARCHAR(20) NOT NULL,
    group_id VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL,
    PRIMARY KEY(self_id,group_id),
    FOREIGN KEY(self_id,group_id) REFERENCES group_policy(self_id,group_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS group_persona (
    self_id VARCHAR(20) NOT NULL,
    group_id VARCHAR(20) NOT NULL,
    prompt VARCHAR(8000) NOT NULL DEFAULT '',
    revision BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY(self_id,group_id),
    FOREIGN KEY(self_id,group_id) REFERENCES group_policy(self_id,group_id) ON DELETE CASCADE
);

