package org.almond_eye_bot;

import org.almond_eye_bot.config.BotConfiguration.*;
import org.almond_eye_bot.config.OneBotProperties;
import org.almond_eye_bot.service.*;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import java.nio.file.*;
import java.sql.DriverManager;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

class DatabaseRuleMigrationTests {
    @TempDir Path directory;
    BotConfigurationService open() throws Exception { return new BotConfigurationService(directory.toString(), new OneBotProperties()); }
    String url(Path root) { return "jdbc:h2:file:" + root.resolve("data/bot-config").toString().replace('\\', '/'); }

    @Test void oldSchemaAndUserRulesArePreservedAndDeletedDefaultsNeverReturn() throws Exception {
        Files.createDirectories(directory.resolve("data"));
        try (var connection = DriverManager.getConnection(url(directory), "sa", ""); var sql = connection.createStatement()) {
            sql.execute("CREATE TABLE reply_rule(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, keyword VARCHAR(200), match_type VARCHAR(10), reply_text VARCHAR(4000), image_id BIGINT, enabled BOOLEAN, priority INTEGER)");
            sql.execute("INSERT INTO reply_rule(keyword,match_type,reply_text,enabled,priority) VALUES('打灰','CONTAINS','原有回复',TRUE,100)");
        }
        var store = open();
        try {
            assertEquals("原有回复", store.match("今天打灰").orElseThrow().text());
            assertEquals("REPLY", store.match("今天打灰").orElseThrow().action());
            assertEquals(1, store.rules().stream().filter(rule -> rule.keyword().equals("打灰")).count());
            assertTrue(store.match("AI 问题").isEmpty());
            assertFalse(store.rules().stream().filter(rule -> rule.action().equals("AI")).findFirst().orElseThrow().enabled());
            for (var rule : store.rules()) store.deleteRule(rule.id());
        } finally { store.close(); }
        store = open();
        try { assertTrue(store.rules().isEmpty()); assertTrue(store.match("AI 问题").isEmpty()); }
        finally { store.close(); }
    }

    @Test void customActionsExtractLiteralArgumentsAndSurviveBackupRestore() throws Exception {
        String backup;
        var store = open();
        try {
            for (var rule : store.rules()) store.deleteRule(rule.id());
            store.saveRule(null, new RuleInput("咨询", "CONTAINS", "请填写：{keyword} 内容", null, true, 10, "AI"));
            assertTrue(store.match("咨询你好").isEmpty());
            var matched = store.match("请咨询　帮助我理解打灰").orElseThrow();
            assertEquals("AI", matched.action()); assertEquals("帮助我理解打灰", matched.argument());
            store.saveRule(null, new RuleInput("a+b?", "CONTAINS", "", null, true, 20, "WIKI"));
            assertEquals("完整 查询词", store.match("a+b? 完整 查询词").orElseThrow().argument());
            assertTrue(store.match("ab 完整 查询词").isEmpty());
            assertThrows(org.springframework.web.server.ResponseStatusException.class,
                    () -> store.saveRule(null, new RuleInput("危险", "CONTAINS", "", null, true, 10, "HTTP_URL")));
            backup = store.exportSql();
        } finally { store.close(); }
        Path restored = directory.resolve("restored"); Files.createDirectories(restored.resolve("data"));
        try (var connection = DriverManager.getConnection(url(restored), "sa", ""); var sql = connection.createStatement()) { sql.execute(backup); }
        var copy = new BotConfigurationService(restored.toString(), new OneBotProperties());
        try {
            assertEquals(2, copy.rules().size()); assertEquals("AI", copy.match("咨询 问题").orElseThrow().action());
            assertTrue(copy.match("AI 问题").isEmpty());
        } finally { copy.close(); }
    }

    @Test void renamedKeywordsExecuteAndDeletedKeywordsHaveNoCodeFallback() throws Exception {
        var store = open();
        try {
            var ai = mock(AiChatService.class); var images = mock(LocalImageService.class);
            var wiki = mock(WikiService.class); var group = mock(GroupAutoReplyService.class);
            var execution = new BotReplyService(ai, images, wiki, store, group);
            var context = new BotReplyService.Context("user", null, null, "user", false, false, false);
            var rule = store.rules().stream().filter(item -> item.keyword().equals("AI")).findFirst().orElseThrow();
            store.saveRule(rule.id(), new RuleInput("咨询", "CONTAINS", rule.replyText(), null, true, 10, "AI"));
            when(ai.chat("user", "帮助我打灰")).thenReturn("最终回复");
            assertEquals("最终回复", execution.execute(store.match("咨询 帮助我打灰").orElseThrow(), context).get(0).text());
            assertTrue(store.match("AI 问题").isEmpty());
            store.deleteRule(rule.id()); assertTrue(store.match("咨询 内容").isEmpty());
            for (var item : store.rules()) if (item.keyword().equals("打灰")) store.deleteRule(item.id());
            new OneBotMessageService(store, execution, group).handleEvent(com.alibaba.fastjson2.JSONObject.of(
                    "self_id", "100", "user_id", "200", "message_type", "private", "message", "打灰"),
                    (action, params) -> fail("Deleted keyword must have no fallback"));
            verifyNoInteractions(images, wiki, group);
            var helpRule = store.rules().stream().filter(item -> item.keyword().equals("help")).findFirst().orElseThrow();
            store.saveRule(helpRule.id(), new RuleInput(helpRule.keyword(), helpRule.matchType(), helpRule.replyText(), null, true, 0, "HELP"));
            String help = execution.execute(store.match("HELP").orElseThrow(), context).get(0).text();
            assertFalse(help.contains("咨询")); assertFalse(help.contains("打灰"));
        } finally { store.close(); }
    }
}
